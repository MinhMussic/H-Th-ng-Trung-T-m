export type ImportType = 'STUDENT' | 'TEACHER' | 'ACCOUNT';

export interface ParsedImportRow {
  rowNumber: number;
  raw: Record<string, any>;
  
  // Normalized profile fields
  code: string;
  fullName: string;
  email: string;
  phone: string;
  gender: Gender;
  birthDate: string;
  address: string;
  subjectsOrSpecialties: string[];
  hourlyRate?: number;
  guardianName?: string;
  guardianPhone?: string;
  guardianRelation?: string;
  status: string;
  notes?: string;

  // Account creation fields
  createAccount: boolean;
  accountRole: UserRole;
  password?: string;

  // Validation
  isValid: boolean;
  errors: string[];
  warnings: string[];
  isDuplicateInFile?: boolean;
  isDuplicateInDB?: boolean;
  codeAutoGenerated?: boolean;
}

/**
 * Normalizes a header string for flexible matching
 */
export const normalizeHeader = (str: string): string => {
  if (!str) return '';
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
};

/**
 * Flexible date parser supporting DD/MM/YYYY, YYYY-MM-DD, Excel serial numbers, Date objects
 */
export const parseFlexibleDate = (val: any): string => {
  if (!val) return '';
  if (val instanceof Date && !isNaN(val.getTime())) {
    return val.toISOString().split('T')[0];
  }
  if (typeof val === 'number') {
    // Excel date serial number check (around 1970 - 2040)
    if (val > 10000 && val < 60000) {
      try {
        const utc_days = Math.floor(val - 25569);
        const date = new Date(utc_days * 86400 * 1000);
        return date.toISOString().split('T')[0];
      } catch (e) {
        return '';
      }
    }
    return String(val);
  }

  const str = String(val).trim();
  if (!str) return '';

  // Match DD/MM/YYYY or DD-MM-YYYY
  const dmyMatch = str.match(/^(\d{1,2})[\/\-\.](\d{1,2})[\/\-\.](\d{4})$/);
  if (dmyMatch) {
    const day = dmyMatch[1].padStart(2, '0');
    const month = dmyMatch[2].padStart(2, '0');
    const year = dmyMatch[3];
    return `${year}-${month}-${day}`;
  }

  // Match YYYY/MM/DD or YYYY-MM-DD
  const ymdMatch = str.match(/^(\d{4})[\/\-\.](\d{1,2})[\/\-\.](\d{1,2})$/);
  if (ymdMatch) {
    const year = ymdMatch[1];
    const month = ymdMatch[2].padStart(2, '0');
    const day = ymdMatch[3].padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  // If only year is provided (e.g. 2015)
  if (/^\d{4}$/.test(str)) {
    return `${str}-01-01`;
  }

  return str;
};

/**
 * Parses gender string
 */
export const parseGender = (val: any): Gender => {
  if (!val) return 'Nam';
  const str = String(val).trim().toLowerCase();
  if (str.includes('nu') || str.includes('nữ') || str.includes('female') || str === 'f') {
    return 'Nữ';
  }
  if (str.includes('khac') || str.includes('khác') || str.includes('other')) {
    return 'Khác';
  }
  return 'Nam';
};

