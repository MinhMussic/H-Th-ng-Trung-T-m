/**
 * Parses an uploaded File (Excel or CSV) into structured data rows
 */
export const parseUploadedFile = async (
  file: File,
  importType: ImportType,
  existingStudents: Student[] = [],
  existingTeachers: Teacher[] = [],
  existingAccounts: UserAccount[] = []
): Promise<ParsedImportRow[]> => {
  const arrayBuffer = await file.arrayBuffer();
  const workbook = XLSX.read(arrayBuffer, { type: 'array', cellDates: true });
  const firstSheetName = workbook.SheetNames[0];
  const worksheet = workbook.Sheets[firstSheetName];

  // Convert to JSON array of objects with header row
  const rawRows: any[] = XLSX.utils.sheet_to_json(worksheet, { defval: '' });

  if (!rawRows || rawRows.length === 0) {
    return [];
  }

  // Pre-calculate sets for duplicate detection
  const existingEmails = new Set(existingAccounts.map(a => (a.email || '').toLowerCase().trim()));
  (existingStudents || []).forEach(s => { if (s.email) existingEmails.add(s.email.toLowerCase().trim()); });
  (existingTeachers || []).forEach(t => { if (t.email) existingEmails.add(t.email.toLowerCase().trim()); });

  const existingStudentCodes = new Set((existingStudents || []).map(s => (s.code || '').toUpperCase().trim()));
  const existingTeacherCodes = new Set((existingTeachers || []).map(t => (t.code || '').toUpperCase().trim()));

  const seenEmailsInFile = new Set<string>();
  const seenCodesInFile = new Set<string>();

  // Determine starting number for auto-generating codes
  let currentStudentSeq = 1;
  existingStudentCodes.forEach(c => {
    const m = c.match(/^HV(\d+)$/i);
    if (m) {
      const n = parseInt(m[1], 10);
      if (!isNaN(n) && n >= currentStudentSeq) currentStudentSeq = n + 1;
    }
  });

  let currentTeacherSeq = 1;
  existingTeacherCodes.forEach(c => {
    const m = c.match(/^GV(\d+)$/i);
    if (m) {
      const n = parseInt(m[1], 10);
      if (!isNaN(n) && n >= currentTeacherSeq) currentTeacherSeq = n + 1;
    }
  });

  const parsedList: ParsedImportRow[] = [];

  rawRows.forEach((row, index) => {
    // Flatten and match row keys using normalizeHeader
    const rowMap: Record<string, any> = {};
    Object.keys(row).forEach(k => {
      rowMap[normalizeHeader(k)] = row[k];
    });

    // Helper to find value from possible aliases
    const findVal = (aliases: string[]) => {
      for (const alias of aliases) {
        const norm = normalizeHeader(alias);
        if (rowMap[norm] !== undefined && rowMap[norm] !== '') {
          return rowMap[norm];
        }
      }
      // Partial search fallback
      for (const k of Object.keys(rowMap)) {
        for (const alias of aliases) {
          const norm = normalizeHeader(alias);
          if (k.includes(norm) && rowMap[k] !== undefined && rowMap[k] !== '') {
            return rowMap[k];
          }
        }
      }
      return '';
    };

    // Extract fields
    const rawFullName = String(findVal(['ho va ten', 'ho ten', 'ten', 'full name', 'fullname', 'name', 'ho va ten hoc vien', 'ho va ten giao vien'])).trim();
    let rawCode = String(findVal(['ma', 'ma hoc vien', 'ma giao vien', 'ma hv', 'ma gv', 'code', 'student code', 'teacher code', 'ma ho so'])).trim().toUpperCase();
    let rawEmail = String(findVal(['email', 'thu dien tu', 'mail', 'dia chi email'])).trim().toLowerCase();
    const rawPhone = String(findVal(['so dien thoai', 'sdt', 'dien thoai', 'phone', 'mobile', 'telephone'])).trim();
    const rawBirthDate = parseFlexibleDate(findVal(['ngay sinh', 'sinh nhat', 'nam sinh', 'dob', 'birthdate', 'birth date']));
    const rawGender = parseGender(findVal(['gioi tinh', 'phai', 'gender', 'sex']));
    const rawAddress = String(findVal(['dia chi', 'noi o', 'ho khau', 'address', 'location'])).trim();
    const rawSubjectsStr = String(findVal(['mon hoc', 'bo mon', 'chuyen mon', 'mon hoc dang ky', 'specialties', 'subject', 'subjects', 'mon'])).trim();
    const rawHourlyRateStr = findVal(['thu lao', 'muc thu lao', 'luong theo gio', 'hourly rate', 'rate', 'thu lao buoi']);
    const rawGuardianName = String(findVal(['ho ten phu huynh', 'phu huynh', 'ten phu huynh', 'nguoi giam ho', 'guardian name', 'parent name'])).trim();
    const rawGuardianPhone = String(findVal(['sdt phu huynh', 'dien thoai phu huynh', 'so dien thoai phu huynh', 'guardian phone', 'parent phone'])).trim();
    const rawGuardianRelation = String(findVal(['moi quan he', 'quan he', 'relation', 'guardian relation'])).trim() || (rawGuardianName ? 'Phụ huynh' : '');
    const rawStatus = String(findVal(['trang thai', 'tinh trang', 'status'])).trim().toLowerCase() || 'active';
    const rawCreateAcc = String(findVal(['tao tai khoan', 'tao tk', 'create account', 'account'])).trim().toLowerCase();
    const rawPassword = String(findVal(['mat khau', 'password', 'mat khau khoi tao', 'pass'])).trim();
    const rawNotes = String(findVal(['ghi chu', 'tieu su', 'gioi thieu', 'note', 'notes', 'bio'])).trim();
    const rawRoleStr = String(findVal(['vai tro', 'role', 'quyen'])).trim().toUpperCase();

    // Skip empty dummy rows
    if (!rawFullName && !rawEmail && !rawCode && !rawPhone) {
      return;
    }

    const errors: string[] = [];
    const warnings: string[] = [];
    let codeAutoGenerated = false;

    // Validate Full Name
    if (!rawFullName) {
      errors.push('Thiếu họ và tên');
    }

    // Auto-generate code if omitted
    if (!rawCode) {
      if (importType === 'STUDENT') {
        rawCode = `HV${String(currentStudentSeq).padStart(3, '0')}`;
        currentStudentSeq++;
        codeAutoGenerated = true;
        warnings.push(`Tự động cấp mã học viên: ${rawCode}`);
      } else if (importType === 'TEACHER') {
        rawCode = `GV${String(currentTeacherSeq).padStart(3, '0')}`;
        currentTeacherSeq++;
        codeAutoGenerated = true;
        warnings.push(`Tự động cấp mã giáo viên: ${rawCode}`);
      }
    }

    // Check code duplication
    let isDuplicateInDB = false;
    let isDuplicateInFile = false;

    if (rawCode) {
      if (seenCodesInFile.has(rawCode)) {
        isDuplicateInFile = true;
        errors.push(`Trùng mã ${rawCode} với dòng khác trong file`);
      } else {
        seenCodesInFile.add(rawCode);
      }

      if (importType === 'STUDENT' && existingStudentCodes.has(rawCode)) {
        isDuplicateInDB = true;
        warnings.push(`Mã ${rawCode} đã tồn tại trong danh sách học viên hiện có`);
      } else if (importType === 'TEACHER' && existingTeacherCodes.has(rawCode)) {
        isDuplicateInDB = true;
        warnings.push(`Mã ${rawCode} đã tồn tại trong danh sách giáo viên hiện có`);
      }
    }

    // Fallback Email if empty
    if (!rawEmail) {
      if (rawFullName && rawCode) {
        // Auto-generate a safe fallback email
        const safeSlug = normalizeHeader(rawFullName).replace(/\s+/g, '.');
        rawEmail = `${safeSlug}.${rawCode.toLowerCase()}@minhmusic.edu.vn`;
        warnings.push(`Tự động tạo email nội bộ: ${rawEmail}`);
      } else {
        errors.push('Thiếu địa chỉ email');
      }
    } else {
      // Validate email format
      const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
      if (!emailRegex.test(rawEmail)) {
        errors.push('Định dạng email không hợp lệ');
      }
    }

    // Check email duplication
    if (rawEmail) {
      if (seenEmailsInFile.has(rawEmail)) {
        isDuplicateInFile = true;
        errors.push(`Trùng email ${rawEmail} với dòng khác trong file`);
      } else {
        seenEmailsInFile.add(rawEmail);
      }

      if (existingEmails.has(rawEmail)) {
        isDuplicateInDB = true;
        warnings.push(`Email ${rawEmail} đã có tài khoản/hồ sơ trong hệ thống`);
      }
    }

    // Parse subjects/specialties array
    let subjectsOrSpecialties: string[] = [];
    if (rawSubjectsStr) {
      subjectsOrSpecialties = rawSubjectsStr
        .split(/[,;\-\/]+/)
        .map(s => s.trim())
        .filter(Boolean);
    }
    if (subjectsOrSpecialties.length === 0) {
      if (importType === 'STUDENT') subjectsOrSpecialties = ['Piano'];
      if (importType === 'TEACHER') subjectsOrSpecialties = ['Piano'];
    }

    // Parse Hourly Rate
    let hourlyRate: number | undefined = undefined;
    if (rawHourlyRateStr) {
      const num = Number(String(rawHourlyRateStr).replace(/[^0-9]/g, ''));
      if (!isNaN(num) && num > 0) hourlyRate = num;
    }

    // Create Account Flag
    let createAccount = true;
    if (rawCreateAcc.includes('khong') || rawCreateAcc.includes('không') || rawCreateAcc === 'false' || rawCreateAcc === '0' || rawCreateAcc === 'no') {
      createAccount = false;
    }

    // Determine Account Role
    let accountRole: UserRole = importType === 'STUDENT' ? 'STUDENT' : importType === 'TEACHER' ? 'TEACHER' : 'STUDENT';
    if (rawRoleStr) {
      if (rawRoleStr.includes('ADMIN') || rawRoleStr.includes('QUẢN TRỊ')) accountRole = 'ADMIN';
      else if (rawRoleStr.includes('TEACHER') || rawRoleStr.includes('GIÁO VIÊN') || rawRoleStr.includes('GV')) accountRole = 'TEACHER';
      else if (rawRoleStr.includes('PARENT') || rawRoleStr.includes('PHỤ HUYNH') || rawRoleStr.includes('PH')) accountRole = 'PARENT';
      else if (rawRoleStr.includes('GUARDIAN') || rawRoleStr.includes('GIÁM HỘ')) accountRole = 'GUARDIAN';
      else accountRole = 'STUDENT';
    }

    const isValid = errors.length === 0;

    parsedList.push({
      rowNumber: index + 2, // 1-based header is row 1
      raw: row,
      code: rawCode,
      fullName: rawFullName,
      email: rawEmail,
      phone: rawPhone,
      gender: rawGender,
      birthDate: rawBirthDate || '2015-01-01',
      address: rawAddress,
      subjectsOrSpecialties,
      hourlyRate,
      guardianName: rawGuardianName,
      guardianPhone: rawGuardianPhone,
      guardianRelation: rawGuardianRelation,
      status: rawStatus.includes('trial') || rawStatus.includes('thử') ? 'trial' : rawStatus.includes('reserve') || rawStatus.includes('bảo lưu') ? 'reserved' : rawStatus.includes('leave') ? 'on_leave' : 'active',
      notes: rawNotes,
      createAccount,
      accountRole,
      password: rawPassword || undefined,
      isValid,
      errors,
      warnings,
      isDuplicateInFile,
      isDuplicateInDB,
      codeAutoGenerated
    });
  });

  return parsedList;
};
